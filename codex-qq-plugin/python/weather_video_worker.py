"""Official weather-video worker. Rendering and encoding never share a heavy process."""
import contextlib
import json
import os
import re
import subprocess
import sys
import time
from threading import Timer, Event
from pathlib import Path

from weather_video_codec import FrameFiles, VideoFailure, finish_video, frame_folder, output_directory
from video_trace import reporting, stage


def read_packet(stream):
    line=stream.readline(65537)
    if not line:return None
    if len(line)>65536:raise ValueError('PACKET_TOO_LARGE')
    return json.loads(line)


def write_packet(stream, value):
    stream.write((json.dumps(value,ensure_ascii=False)+'\n').encode());stream.flush()


def prepare(job_name, profiled=False):
    # This identifier is generated by the parent, outside the model/tool schema.
    directory=Path.cwd()/'.private/weather-video';job=directory/job_name
    if not re.fullmatch(r'job-[a-f0-9]{32}',job_name) or job.is_symlink() or job.resolve().parent!=directory.resolve():raise ValueError('INVALID_JOB')
    receipt=sys.stdout.buffer
    args=read_packet(sys.stdin.buffer)
    try:
        emit=(lambda event:write_packet(receipt,{'type':'video_stage',**event})) if profiled else None
        with open(os.devnull,'w') as quiet,contextlib.redirect_stdout(quiet),contextlib.redirect_stderr(quiet),reporting(emit):
            with stage('video_prepare_worker'):
                from weather_video import build_tool
                tool=build_tool(Path.cwd()/'.private',frame_output=FrameFiles(job))
            data=tool.invoke(args)
    except Exception:
        data={'ok':False,'code':'VIDEO_SOURCE_UNAVAILABLE'}
    write_packet(receipt,data)


def run_prepare(job, args, deadline, emit):
    command=[sys.executable,'-u',str(Path(__file__).resolve()),'--prepare',job.name]
    if emit:command.append('--timing')
    with subprocess.Popen(command,stdin=subprocess.PIPE,stdout=subprocess.PIPE,stderr=subprocess.DEVNULL,
                          env={**os.environ,'OPENBLAS_NUM_THREADS':'1'},
                          creationflags=subprocess.CREATE_NO_WINDOW if os.name=='nt' else 0) as child:
        expired=Event()
        def expire():
            expired.set();child.kill()
        timer=Timer(max(.1,deadline-time.monotonic()),expire)
        timer.start()
        try:
            write_packet(child.stdin,args);child.stdin.close()
            data=None
            for _ in range(32):
                packet=read_packet(child.stdout)
                if packet is None:break
                if not isinstance(packet,dict) or data is not None:raise VideoFailure('VIDEO_ENCODING_FAILED')
                if emit and packet.get('type')=='video_stage':
                    emit(packet)
                else:data=packet
            else:raise VideoFailure('VIDEO_ENCODING_FAILED')
            child.wait()
            if expired.is_set():raise VideoFailure('VIDEO_TIMEOUT')
            if child.returncode or data is None:raise VideoFailure('VIDEO_ENCODING_FAILED')
            return data
        finally:
            timer.cancel()
            if child.poll() is None:child.kill()


def generate(args, emit=None):
    deadline=time.monotonic()+170
    directory=output_directory(Path.cwd()/'.private')
    with frame_folder(directory) as job:
        data=run_prepare(job,args,deadline,emit)
        if not isinstance(data,dict):raise VideoFailure('VIDEO_ENCODING_FAILED')
        if not data.get('ok'):return data
        if data.get('format_version')!=2 or data.get('layer')!=args.get('layer'):
            raise VideoFailure('VIDEO_ENCODING_FAILED')
        with reporting(emit),stage('video_encode_h264'):
            return finish_video(job,data,directory,deadline)


def serve():
    while True:
        packet=read_packet(sys.stdin.buffer)
        if packet is None:return
        result={'type':'result','id':packet.get('id'),'kind':'analysis'}
        try:
            if packet.get('type')!='weather_video':raise ValueError('UNSUPPORTED')
            def emit(event):
                write_packet(sys.stdout.buffer,{**event,'type':'video_stage','id':packet['id']})
            result['data']=generate(packet.get('args',{}),emit if packet.get('_traceVideo') is True else None)
        except VideoFailure as error:
            result['data']={'ok':False,'code':error.code}
        except Exception:
            result['data']={'ok':False,'code':'VIDEO_SOURCE_UNAVAILABLE'}
        write_packet(sys.stdout.buffer,result)


if __name__=='__main__':
    if len(sys.argv) in (3,4) and sys.argv[1]=='--prepare':prepare(sys.argv[2],sys.argv[3:]==['--timing'])
    elif not sys.argv[1:]:serve()
    else:raise SystemExit(2)
